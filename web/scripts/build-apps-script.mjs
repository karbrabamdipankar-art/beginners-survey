// Generates two Apps Script files from the single sources of truth:
//   apps-script/Engine.js       the web app's logic engine, bundled (global BeginnersEngine)
//   apps-script/Instruments.js  the deployable instruments + system_fill + route_check
// Both are generated (git-ignored). Run before `clasp push` and before the Apps Script tests.
import { build } from 'esbuild';
import { writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildRegistry } from './copy-instruments.mjs';

const webDir = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const outDir = resolve(webDir, '..', 'apps-script');
const banner = '// GENERATED by web/scripts/build-apps-script.mjs. Do not edit; edit /web/src or /questionnaires instead.\n';

await build({
  entryPoints: [join(webDir, 'src', 'engine', 'server-entry.ts')],
  bundle: true,
  format: 'iife',
  globalName: 'BeginnersEngine',
  target: 'es2019',
  platform: 'neutral',
  outfile: join(outDir, 'Engine.js'),
  banner: { js: banner },
  legalComments: 'none',
});

const { index, files } = buildRegistry();
const registry = {};
for (const e of index) {
  registry[e.instrument_version_id] = { instrument: files[e.file], system_fill: e.system_fill, route_check: e.route_check };
}
writeFileSync(join(outDir, 'Instruments.js'), `${banner}var INSTRUMENT_REGISTRY = ${JSON.stringify(registry)};\n`);
console.log(`Wrote Engine.js and Instruments.js (${index.length} instruments) to apps-script/`);
